/**
 * @brief Executes Cartesian motion on top of the Joint Trajectory Controller (JTC).
 *
 * Accepts a MultiDOFJointTrajectory of end-effector poses (single pose or an action chunk),
 * interpolates it in Cartesian space (cubic-spline translation + SLERP orientation), resamples the
 * path densely and runs differential inverse kinematics to produce an ordinary joint-space
 * trajectory. The joint trajectory is handed to JTC, whose update loop executes it unchanged.
 *
 * IK runs once per incoming message in the (non-RT) subscription callback, so the real-time loop
 * stays pure JTC. The ``joints`` parameter names the real robot joints; the kinematics plugin
 * (kinematics_interface, KDL by default) provides the forward kinematics and Jacobian.
 */
